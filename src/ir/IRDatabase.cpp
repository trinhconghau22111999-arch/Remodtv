#include "IRDatabase.h"
#include <QJsonArray>
#include <QJsonObject>
#include <QStandardPaths>
#include <QDebug>

IRDatabase* IRDatabase::s_instance = nullptr;

IRDatabase* IRDatabase::instance() {
    if (!s_instance) s_instance = new IRDatabase();
    return s_instance;
}

IRDatabase::IRDatabase(QObject *parent) : QObject(parent) {
    loadBuiltinCodes();
}

void IRDatabase::loadBuiltinCodes() {
    m_devices << buildSamsung();
    m_devices << buildLG();
    m_devices << buildSony();
    m_devices << buildToshiba();
    m_devices << buildPhilips();
    m_devices << buildSharp();
    m_devices << buildTCL();
    m_devices << buildXiaomi();
    qDebug() << "IR Database loaded:" << m_devices.size() << "brands";
}

QStringList IRDatabase::availableBrands() const {
    QStringList brands;
    for (const auto &d : m_devices) brands << d.brand;
    return brands;
}

QList<IRDevice> IRDatabase::findByBrand(const QString &brand) const {
    QList<IRDevice> result;
    for (const auto &d : m_devices)
        if (d.brand.toLower() == brand.toLower()) result << d;
    return result;
}

IRDevice IRDatabase::bestMatch(const QString &brand) const {
    auto list = findByBrand(brand);
    return list.isEmpty() ? IRDevice{} : list.first();
}

